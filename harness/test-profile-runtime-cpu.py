def compile_stub(directory, name, *defines, source=STUB_C):
    """A real ELF ctypes library (default: the NVFP4 entry points; no CUDA); None without a C compiler."""
    compiler = shutil.which('gcc') or shutil.which('cc')
    if compiler is None:
        return None
    directory = pathlib.Path(directory)
    source_path = directory / (name + '.c')
    source_path.write_bytes(source)
    target = directory / name
    subprocess.run([compiler, '-shared', '-fPIC', '-O0', *['-D' + item for item in defines], '-o', str(target),
                    str(source_path)], check=True, capture_output=True, timeout=120)
    return target


