class Tree:
    """Installed-layout synthetic ROOT: managed files, runtime tree, optional gate library."""

    def __init__(self, root, profiles, library=True, extra_runtime=None, cache_modules=None):
        self.root = pathlib.Path(root)
        self.profiles = profiles
        for name in sorted(runtime.MANAGED_FILES):
            data = json.dumps(profiles).encode() if name == 'profiles.json' else ('# ' + name + '\n').encode()
            self.write(name, data)
        self.runtime = dict(RUNTIME_FILES, **KERNEL_SOURCES, **EXTENSION_SO, **{'kernel/kernel_provenance.py': KP_BYTES},
                            **(extra_runtime or {}))
        for relative, data in {**self.runtime, **IGNORED_RUNTIME_FILES}.items():
            self.write(runtime.RUNTIME_PREFIX + relative, data)
        manifest = kernel_manifest(self.root / runtime.RUNTIME_PREFIX / 'kernel', runtime.kernel_cache_dir(), cache_modules)
        self.runtime['kernel/kernel_cache_manifest.json'] = manifest
        self.write(runtime.KERNEL_PROVENANCE_MANIFEST, manifest)
        if library:
            self.write(runtime.GATE_LIBRARY, b'\x7fELF synthetic gate')
        (self.root / 'config').mkdir(exist_ok=True)

    def write(self, relative, data):
        path = self.root / relative
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        return path

    def save_profiles(self, profiles):
        self.profiles = profiles
        self.write('profiles.json', json.dumps(profiles).encode())

    def sources(self):
        result = {name: self.root / name for name in runtime.MANAGED_FILES}
        for relative in self.runtime:
            result[runtime.RUNTIME_PREFIX + relative] = self.root / runtime.RUNTIME_PREFIX / relative
        for library in sorted(runtime.LIBRARY_ENV):
            if (self.root / library).exists():
                result[library] = self.root / library
        return result

    def receipt(self, profiles=None, sources=None, statuses=None):
        """What make-qualification writes: kernel provenance computed live, library bindings as recorded."""
        profiles = self.profiles if profiles is None else profiles
        sources = self.sources() if sources is None else sources
        statuses = statuses or {}
        source_files = {rel: sha(pathlib.Path(path).read_bytes()) for rel, path in sources.items()}
        records = {}
        for name, profile in profiles['profiles'].items():
            if profile['qualified'] is True:
                status, limits = statuses.get(name, ('accepted', []))
                records[name] = {'configuration_sha256': runtime.canonical_profile_sha256(profile),
                                 'acceptance_status': status, 'known_limitations': limits,
                                 'evidence': copy.deepcopy(EVIDENCE)}
                switches = [s for s in runtime.CUDA_EVIDENCE_SWITCHES if profile.get(s) is True]
                if switches:
                    records[name]['evidence'] += copy.deepcopy(CUDA_EVIDENCE)
                for switch in switches:
                    library = runtime.NATIVE_LIBRARIES[switch][1]
                    records[name][switch] = {
                        'library': library, 'library_sha256': source_files.get(library),
                        'run_receipts': [CUDA_EVIDENCE[0]['path']], 'bitexact_reports': [CUDA_EVIDENCE[1]['path']]}
        native = {library: {'env': runtime.LIBRARY_ENV[library], 'sha256': source_files[library],
                            'abi': runtime.LIBRARY_ABI.get(library, {})}
                  for library in runtime.required_libraries(profiles) if library in source_files}
        return {'schema': 1, 'checkpoint': dict(runtime.CHECKPOINT), 'profiles': records,
                'source_files': source_files, 'environment': runtime.runtime_environment(),
                'kernel_provenance': runtime.kernel_provenance_record(profiles, source_files, lambda rel: sources[rel],
                                                                     runtime.kernel_cache_dir()),
                'native_libraries': native}

    def install_receipt(self, receipt=None):
        receipt = self.receipt() if receipt is None else receipt
        self.write(runtime.QUALIFICATION_RECEIPT, json.dumps(receipt).encode())
        return receipt

    def resolver(self):
        sources = self.sources()

        def resolve(relative):
            if relative not in sources:
                raise ValueError('not staged')
            return sources[relative]
        return resolve


